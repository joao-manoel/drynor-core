package org.darkan.core.gameval

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import java.io.File
import java.nio.file.Files
import kotlin.random.Random
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

/**
 * Half of these run against a synthetic catalog folder so they always execute; the rest read the
 * real `gamevals/` catalogs and skip themselves for any type whose file is not there yet (the
 * catalogs are generated by a separate workflow and may be absent or mid-write).
 */
class GamevalTest {

    private val tempDirs = mutableListOf<File>()

    /** `deleteOnExit` never removes a non-empty directory, so the synthetic catalogs are deleted explicitly. */
    @AfterTest
    fun deleteSyntheticCatalogs() {
        tempDirs.forEach { it.deleteRecursively() }
        tempDirs.clear()
    }

    private fun synthetic(): GamevalCatalog {
        val dir = Files.createTempDirectory("gameval-test").toFile()
        tempDirs += dir
        File(dir, "seq.json").writeText(
            """{"revision":727,"type":"seq","entries":{"0":"swarm_walk","1":"seq_1","2":"swarm_attack"}}""",
        )
        File(dir, "clientscript.json").writeText(
            """{"revision":727,"type":"clientscript","entries":{"0":"[proc,script0]","1":"cs2_1"}}""",
        )
        File(dir, "component.json").writeText(
            """{"revision":727,"type":"component","entries":{"548:1":"toplevel:root","548:2":"component_548_2"}}""",
        )
        File(dir, "npc.json").writeText("{ this is not json")
        return GamevalCatalog(dir, retryMillis = 0L)
    }

    @Test
    fun `names resolve and placeholders are hidden`() {
        val g = synthetic()
        assertEquals("swarm_walk", g.name("seq", 0))
        assertNull(g.name("seq", 1), "placeholder must not be reported as a name")
        assertEquals("seq_1", g.rawName("seq", 1))
        assertTrue(g.isPlaceholder("seq", 1))
        assertFalse(g.isPlaceholder("seq", 0))
        assertFalse(g.isPlaceholder("seq", 99))
        assertNull(g.name("seq", 99))
        assertEquals("swarm_walk (0)", g.label("seq", 0))
        assertEquals("1", g.label("seq", 1))
        assertEquals(mapOf(0 to "swarm_walk", 2 to "swarm_attack"), g.entries("seq"))
        assertEquals(3, g.allEntries("seq").size)
        assertTrue(g.has("seq"))
        assertEquals(GamevalCatalog.Source.FOLDER, g.source("seq"))
    }

    @Test
    fun `reverse lookup ignores placeholders`() {
        val g = synthetic()
        assertEquals(2, g.id("seq", "swarm_attack"))
        assertEquals(2, g.requireId("seq", "swarm_attack"))
        assertNull(g.id("seq", "seq_1"))
        assertNull(g.id("seq", "nope"))
        assertFailsWith<IllegalStateException> { g.requireId("seq", "nope") }
        assertNull(g.name("clientscript", 1))
        assertEquals("[proc,script0]", g.name("clientscript", 0))
        assertEquals(0, g.id("clientscript", "[proc,script0]"))
    }

    @Test
    fun `missing and malformed catalogs are empty`() {
        val g = synthetic()
        assertFalse(g.has("npc"))
        assertNull(g.name("npc", 0))
        assertTrue(g.entries("npc").isEmpty())
        assertEquals(GamevalCatalog.Source.MISSING, g.source("npc"))
        assertFalse(g.has("obj"))
        assertNull(g.id("obj", "anything"))
        assertFailsWith<IllegalStateException> { g.requireId("obj", "anything") }
    }

    @Test
    fun `component packing helpers`() {
        assertEquals(548 shl 16 or 1, GamevalCatalog.pack(548, 1))
        assertEquals(548, GamevalCatalog.ifaceOf(GamevalCatalog.pack(548, 1)))
        assertEquals(1, GamevalCatalog.compOf(GamevalCatalog.pack(548, 1)))
        assertEquals(65535, GamevalCatalog.compOf(GamevalCatalog.pack(1, 65535)))
        assertEquals("548:1", GamevalCatalog.componentKey(548, 1))
        assertEquals("component_548_2", GamevalCatalog.placeholder("component", "548:2"))
        assertEquals("cs2_7", GamevalCatalog.placeholder("clientscript", "7"))
        assertEquals("loc_7", GamevalCatalog.placeholder("loc", "7"))

        val g = synthetic()
        assertEquals("toplevel:root", g.component(548, 1))
        assertEquals("toplevel:root", g.component(GamevalCatalog.pack(548, 1)))
        assertNull(g.component(548, 2), "placeholder component must not be reported as a name")
        assertNull(g.component(548, 3))
        assertEquals("toplevel:root (548:1)", g.componentLabel(548, 1))
        assertEquals("548:2", g.componentLabel(548, 2))
        assertEquals(GamevalCatalog.pack(548, 1), g.componentId("toplevel:root"))
        assertEquals(GamevalCatalog.pack(548, 1), g.requireComponentId("toplevel:root"))
        assertNull(g.componentId("component_548_2"))
        assertFailsWith<IllegalStateException> { g.requireComponentId("nope") }
    }

    // ---- against the real catalogs; each skips when its file is not there ----------------------

    private val real = File(Gameval.folder, "clientscript.json")

    @Test
    fun `clientscript 0 matches the catalog file`() {
        if (!real.isFile || !Gameval.has(Gameval.CLIENTSCRIPT)) return
        val entries = Json.parseToJsonElement(real.readText()).jsonObject["entries"]!!.jsonObject
        val stored = entries["0"]?.jsonPrimitive?.content ?: return
        assertEquals(stored, Gameval.rawName(Gameval.CLIENTSCRIPT, 0))
        if (stored == "cs2_0") assertNull(Gameval.name(Gameval.CLIENTSCRIPT, 0))
        else assertEquals(stored, Gameval.name(Gameval.CLIENTSCRIPT, 0))
    }

    @Test
    fun `placeholders read as null and named entries round-trip`() {
        val random = Random(727)
        for (type in Gameval.TYPES) {
            if (type == Gameval.COMPONENT || !Gameval.has(type)) continue
            val all = Gameval.allEntries(type)
            val placeholder = all.entries.firstOrNull { (id, raw) -> raw == GamevalCatalog.placeholder(type, id.toString()) }
            if (placeholder != null) {
                assertNull(Gameval.name(type, placeholder.key), "$type ${placeholder.key} is a placeholder")
                assertTrue(Gameval.isPlaceholder(type, placeholder.key))
                assertNull(Gameval.id(type, placeholder.value), "$type placeholder must not reverse-resolve")
            }
            val named = Gameval.entries(type)
            if (named.isEmpty()) continue
            val (id, name) = named.entries.elementAt(random.nextInt(named.size))
            assertEquals(id, Gameval.id(type, name), "$type '$name' should round-trip to $id")
            assertEquals(id, Gameval.requireId(type, name))
            assertEquals("$name ($id)", Gameval.label(type, id))
        }
    }

    @Test
    fun `real components pack and unpack`() {
        if (!Gameval.has(Gameval.COMPONENT)) return
        val raw = Gameval.rawEntries(Gameval.COMPONENT)
        val (key, name) = raw.entries.firstOrNull { (k, n) -> n != GamevalCatalog.placeholder(Gameval.COMPONENT, k) } ?: return
        val (iface, comp) = key.split(':').map { it.toInt() }
        assertEquals(name, Gameval.component(iface, comp))
        val packed = assertNotNull(Gameval.componentId(name))
        assertEquals(iface, GamevalCatalog.ifaceOf(packed))
        assertEquals(comp, GamevalCatalog.compOf(packed))
        assertEquals(name, Gameval.component(packed))
    }
}
