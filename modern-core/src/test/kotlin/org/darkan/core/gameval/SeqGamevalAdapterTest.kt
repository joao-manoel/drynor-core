package org.darkan.core.gameval

import com.google.gson.Gson
import com.google.gson.annotations.JsonAdapter
import com.google.gson.stream.JsonReader
import com.google.gson.stream.JsonWriter
import java.io.File
import java.io.StringReader
import java.io.StringWriter
import java.nio.file.Files
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * The combat defs animation fields read and write both forms a data file can hold: a seq id, or
 * the sequence's gameval name. The always-run half uses a synthetic catalog; the @JsonAdapter
 * wiring runs against the real `gamevals/` and skips itself when seq.json is not there (the
 * catalogs are generated by a separate workflow and may be absent or mid-write).
 */
class SeqGamevalAdapterTest {

    private val tempDirs = mutableListOf<File>()

    /** `deleteOnExit` never removes a non-empty directory, so the synthetic catalogs are deleted explicitly. */
    @AfterTest
    fun deleteSyntheticCatalogs() {
        tempDirs.forEach { it.deleteRecursively() }
        tempDirs.clear()
    }

    private fun synthetic(): GamevalCatalog {
        val dir = Files.createTempDirectory("seqgameval-test").toFile()
        tempDirs += dir
        File(dir, "seq.json").writeText(
            """{"revision":727,"type":"seq","entries":{"0":"swarm_walk","1":"seq_1","2":"swarm_attack","416":"human_staff_def"}}""",
        )
        return GamevalCatalog(dir, retryMillis = 0L)
    }

    private fun read(json: String, catalog: GamevalCatalog): Int =
        JsonReader(StringReader(json)).use { SeqGamevalAdapter(catalog).read(it) }

    private fun write(value: Int?, catalog: GamevalCatalog): String {
        val out = StringWriter()
        JsonWriter(out).use { SeqGamevalAdapter(catalog).write(it, value) }
        return out.toString()
    }

    @Test
    fun `reads ids, quoted ids and names`() {
        val g = synthetic()
        assertEquals(416, read("416", g))
        assertEquals(416, read("\"416\"", g), "a quoted id is still an id")
        assertEquals(2, read("\"swarm_attack\"", g))
    }

    @Test
    fun `an unresolvable name reads as minus one`() {
        val g = synthetic()
        assertEquals(-1, read("\"nope\"", g))
        assertEquals(-1, read("\"seq_1\"", g), "a placeholder is not a name")
        assertEquals(-1, read("\"-1\"", g))
    }

    @Test
    fun `writes a name when the catalog has one and the id otherwise`() {
        val g = synthetic()
        assertEquals("\"swarm_walk\"", write(0, g), "seq 0 is a real named sequence, not the 'none' sentinel")
        assertEquals("\"swarm_attack\"", write(2, g))
        assertEquals("\"human_staff_def\"", write(416, g))
        assertEquals("99", write(99, g), "an id with no name writes as the id")
        assertEquals("-1", write(-1, g))
        assertEquals("null", write(null, g))
    }

    // ---- against the real catalog; skips when seq.json is not there -----------------------------

    /** A seq field annotated the way the combat defs loader annotates its four. */
    private class Holder {
        @JsonAdapter(SeqGamevalAdapter::class)
        var anim: Int? = null
    }

    @Test
    fun `gson wires the annotation through the real catalog`() {
        if (!Gameval.has(Gameval.SEQ)) return
        val named = Gameval.entries(Gameval.SEQ).entries.firstOrNull() ?: return
        val gson = Gson()
        val def = gson.fromJson("""{"anim":"${named.value}"}""", Holder::class.java)
        assertEquals(named.key, def.anim)
        val written = gson.toJson(def)
        assertTrue(written.contains("\"${named.value}\""), "written form should carry the name: $written")
        assertEquals(named.key, gson.fromJson(written, Holder::class.java).anim)
    }
}